const ANGLES = [
  "Угол 1: сильный крючок-вопрос или неожиданный факт в начале.",
  "Угол 2: мини-история, кейс или «было / стало».",
  "Угол 3: экспертный разбор или короткий чек-лист.",
  "Угол 4: миф vs реальность, опровержение типичной ошибки.",
];

const TONE_GUIDES = {
  engaging:
    "Тон: вовлекающий. Пиши так, чтобы хотелось дочитать и ответить. Вопросы, «мы вместе», живой ритм.",
  selling:
    "Тон: продающий. Польза, оффер, снятие возражения, ясная выгода. Без агрессивного спама.",
  humor:
    "Тон: юмор. Лёгкая ирония, неожиданное сравнение, без пошлости и без шуток «ниже пояса».",
  expert:
    "Тон: экспертный. Спокойная точность, факты, структура, уважение к читателю. Без занудства.",
  friendly:
    "Тон: дружелюбный. Тепло, просто, как сообщение знакомому. Без сюсюканья.",
  bold:
    "Тон: дерзкий. Смелый тезис, резкая формулировка, уверенность. Без токсичности и оскорблений.",
};

export function buildPrompt({ topic, platform, angleIndex = 0, extra, tone = "engaging" }) {
  const guide = PLATFORM_GUIDES[platform] || PLATFORM_GUIDES.telegram;
  const angle = ANGLES[angleIndex % ANGLES.length];
  const extraLine = extra ? `\nДополнительное требование: ${extra}` : "";
  const toneLine = TONE_GUIDES[tone] || TONE_GUIDES.engaging;

  return `Ты — старший SMM-редактор. Сгенерируй ОДИН готовый пост на русском языке.

Тема / бизнес / идея:
"""
${topic.trim()}
"""

${guide}
${toneLine}
${angle}${extraLine}

Требования:
- Пиши так, будто пост уже можно публиковать.
- Не используй кавычки-обёртки, префиксы вроде «Конечно» и пояснения вне формата.
- Не нумеруй пункты как «Вариант 1».
- IMAGE_PROMPT — подробный промпт НА АНГЛИЙСКОМ для генерации обложки/картинки к посту: сцена, свет, стиль, композиция, цветовая гамма. Без текста на картинке, если это не логотип. 1–3 предложения.

Верни СТРОГО такой формат и ничего больше:

###TITLE
заголовок

###BODY
текст поста

###CTA
призыв к действию

###HASHTAGS
#тег #тег

###IMAGE_PROMPT
english image prompt`;
}
